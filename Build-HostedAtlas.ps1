param(
    [int]$Workers = 3,
    [switch]$Resume
)

$ErrorActionPreference = 'Stop'
$sourceRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'workspace\preprocessed'))
$artworkRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'workspace\scenes\artwork'))
$webRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'HostedAtlas'))
$dataRoot = Join-Path $webRoot 'r2-data'
$workerScript = Join-Path $PSScriptRoot 'Convert-HostedAtlasAssets.ps1'
$ffmpeg = (Get-Command ffmpeg -ErrorAction Stop).Source

if (-not (Test-Path -LiteralPath (Join-Path $sourceRoot 'manifest.json'))) { throw "Prepared room manifest is missing: $sourceRoot" }
if (-not (Test-Path -LiteralPath $artworkRoot)) { throw "Cached Silksong artwork is missing: $artworkRoot" }
if ($Workers -lt 1 -or $Workers -gt 6) { throw 'Workers must be between 1 and 6.' }

# This output folder is generated by this script. Keep cleanup confined to its fixed D: workspace path.
$expectedRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'HostedAtlas'))
if (-not [string]::Equals($webRoot, $expectedRoot, [StringComparison]::OrdinalIgnoreCase)) { throw "Refusing an unexpected output location: $webRoot" }
[IO.File]::WriteAllText((Join-Path $webRoot 'DATA-EXPORT-STATUS.txt'), "Silksong GauntletSong Atlas data export in progress`r`n`r`nStarted: $([DateTimeOffset]::Now.ToString('u'))`r`nData folder: $dataRoot`r`nDo not upload until the conversion completes and Audit-HostedAtlas.ps1 passes.`r`n", [Text.UTF8Encoding]::new($false))
$oldAuditPath = Join-Path $webRoot 'AUDIT-REPORT.json'
if (Test-Path -LiteralPath $oldAuditPath) { Remove-Item -LiteralPath $oldAuditPath -Force }
if (-not $Resume -and (Test-Path -LiteralPath $dataRoot)) { Remove-Item -LiteralPath $dataRoot -Recurse -Force }
New-Item -ItemType Directory -Path $dataRoot -Force | Out-Null
foreach ($name in @('images', 'maps', 'rooms', 'artwork')) { New-Item -ItemType Directory -Path (Join-Path $dataRoot $name) -Force | Out-Null }
foreach ($pattern in @('asset-worker-*.log', 'asset-worker-*.out.log', 'asset-worker-*.err.log', 'asset-tasks*.json', 'asset-progress.txt')) {
    Get-ChildItem -LiteralPath $webRoot -Filter $pattern -File -ErrorAction SilentlyContinue | Remove-Item -Force
}

function Get-PngDimensions([string]$Path) {
    $stream = [IO.File]::OpenRead($Path)
    try {
        $header = New-Object byte[] 24
        if ($stream.Read($header, 0, $header.Length) -ne $header.Length) { throw "PNG header is incomplete: $Path" }
        if ([BitConverter]::ToString($header[0..7]) -ne '89-50-4E-47-0D-0A-1A-0A') { throw "Not a PNG image: $Path" }
        $width = ($header[16] * 16777216) + ($header[17] * 65536) + ($header[18] * 256) + $header[19]
        $height = ($header[20] * 16777216) + ($header[21] * 65536) + ($header[22] * 256) + $header[23]
        return [pscustomobject]@{ Width = [int]$width; Height = [int]$height }
    } finally { $stream.Dispose() }
}

function Write-GzipJson([string]$Json, [string]$OutputPath) {
    $temporaryPath = $OutputPath + '.' + [guid]::NewGuid().ToString('N') + '.tmp'
    $output = [IO.File]::Open($temporaryPath, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
    try {
        $gzip = [IO.Compression.GZipStream]::new($output, [IO.Compression.CompressionLevel]::Optimal, $false)
        try {
            $writer = [IO.StreamWriter]::new($gzip, [Text.UTF8Encoding]::new($false))
            try { $writer.Write($Json) } finally { $writer.Dispose() }
        } finally { $gzip.Dispose() }
    } finally { $output.Dispose() }
    Move-Item -LiteralPath $temporaryPath -Destination $OutputPath -Force
}

$tasks = [Collections.Generic.List[object]]::new()
$roomImageExtensions = [Collections.Generic.Dictionary[string, string]]::new([StringComparer]::OrdinalIgnoreCase)
$oversizedNames = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$roomImages = @(Get-ChildItem -LiteralPath (Join-Path $sourceRoot 'images') -Filter '*.png' -File | Where-Object { $_.Name -notmatch '-native' })
foreach ($file in $roomImages) {
    $dimensions = Get-PngDimensions $file.FullName
    $oversized = $dimensions.Width -gt 16383 -or $dimensions.Height -gt 16383
    $extension = if ($oversized) { 'png' } else { 'webp' }
    $roomImageExtensions.Add($file.BaseName, $extension)
    if ($oversized) { [void]$oversizedNames.Add($file.BaseName) }
    $tasks.Add([pscustomobject]@{
        Source = $file.FullName
        Destination = (Join-Path (Join-Path $dataRoot 'images') ($file.BaseName + '.' + $extension))
        Mode = $(if ($oversized) { 'copy' } else { 'webp' })
        Width = $dimensions.Width
        Height = $dimensions.Height
    })
}

foreach ($file in Get-ChildItem -LiteralPath (Join-Path $sourceRoot 'maps') -Filter '*.png' -File | Where-Object { $_.Name -notmatch '-native' }) {
    $dimensions = Get-PngDimensions $file.FullName
    $tasks.Add([pscustomobject]@{ Source = $file.FullName; Destination = (Join-Path (Join-Path $dataRoot 'maps') ($file.BaseName + '.webp')); Mode = 'webp'; Width = $dimensions.Width; Height = $dimensions.Height })
}
foreach ($file in Get-ChildItem -LiteralPath $artworkRoot -Filter '*.png' -File) {
    $dimensions = Get-PngDimensions $file.FullName
    $tasks.Add([pscustomobject]@{ Source = $file.FullName; Destination = (Join-Path (Join-Path $dataRoot 'artwork') ($file.BaseName + '.webp')); Mode = 'webp'; Width = $dimensions.Width; Height = $dimensions.Height })
}

function Rewrite-ImageReferences([string]$Json) {
    $evaluator = [System.Text.RegularExpressions.MatchEvaluator]{
        param($match)
        $folder = $match.Groups['folder'].Value
        $base = $match.Groups['base'].Value
        $extension = 'webp'
        if ($folder -eq 'images' -and $oversizedNames.Contains($base)) { $extension = 'png' }
        return $match.Groups['prefix'].Value + $folder + '/' + $base + '.' + $extension + $match.Groups['suffix'].Value
    }
    $rewritten = [regex]::Replace($Json, '(?<prefix>"(?:file|image|previewFile|previewImage)"\s*:\s*")(?<folder>images|maps)/(?<base>[^"/]+)\.png(?<suffix>")', $evaluator)
    $doubleEncodedMiddleDot = [string]::Concat([char]0x00C3, [char]0x201A, [char]0x00C2, [char]0x00B7)
    $singleEncodedMiddleDot = [string]::Concat([char]0x00C2, [char]0x00B7)
    return $rewritten.Replace($doubleEncodedMiddleDot, [string][char]0x00B7).Replace($singleEncodedMiddleDot, [string][char]0x00B7)
}

Write-Output ("Found {0} clean room renders; {1} exceed WebP's 16,383-pixel side limit and will be preserved as PNG." -f $roomImages.Count, $oversizedNames.Count)
Write-Output ("Preparing {0} game-derived image files, including the cached texture atlases once each." -f $tasks.Count)
Write-Output 'Compressing JSON sidecars while preserving exact per-image file type references.'

$manifestPath = Join-Path $sourceRoot 'manifest.json'
$manifestJson = Rewrite-ImageReferences ([IO.File]::ReadAllText($manifestPath, [Text.Encoding]::UTF8))
Write-GzipJson -Json $manifestJson -OutputPath (Join-Path $dataRoot 'manifest.json.gz')

$navigationPath = Join-Path $sourceRoot 'maps\navigation.json'
if (Test-Path -LiteralPath $navigationPath) {
    $navigationJson = Rewrite-ImageReferences ([IO.File]::ReadAllText($navigationPath, [Text.Encoding]::UTF8))
    Write-GzipJson -Json $navigationJson -OutputPath (Join-Path (Join-Path $dataRoot 'maps') 'navigation.json.gz')
}

$roomFiles = @(Get-ChildItem -LiteralPath (Join-Path $sourceRoot 'rooms') -Filter '*.json' -File | Where-Object { $_.Name -notmatch '-native' })
for ($index = 0; $index -lt $roomFiles.Count; $index++) {
    $file = $roomFiles[$index]
    $outputPath = Join-Path (Join-Path $dataRoot 'rooms') ($file.Name + '.gz')
    $json = [IO.File]::ReadAllText($file.FullName, [Text.Encoding]::UTF8)
    $json = Rewrite-ImageReferences $json
    if (-not $oversizedNames.Contains($file.BaseName)) {
        $json = [regex]::Replace($json, '(?<prefix>"mimeType"\s*:\s*")image/png(?<suffix>")', '${prefix}image/webp${suffix}')
    }
    Write-GzipJson -Json $json -OutputPath $outputPath
    if (($index + 1) % 50 -eq 0 -or $index + 1 -eq $roomFiles.Count) { Write-Output ("Compressed room metadata {0}/{1}" -f ($index + 1), $roomFiles.Count) }
}

$indexRecords = foreach ($task in $tasks) {
    [pscustomobject]@{
        file = $task.Destination.Substring($dataRoot.Length + 1).Replace('\', '/')
        source = [IO.Path]::GetFileName($task.Source)
        format = [IO.Path]::GetExtension($task.Destination).TrimStart('.').ToLowerInvariant()
        width = $task.Width
        height = $task.Height
        sourceBytes = (Get-Item -LiteralPath $task.Source).Length
        mode = $task.Mode
    }
}
$assetIndexJson = ConvertTo-Json -InputObject ([pscustomobject]@{ schemaVersion = 1; source = 'Silksong bundle-derived preprocessed artwork'; imageCount = $tasks.Count; oversizedPngCount = $oversizedNames.Count; images = @($indexRecords) }) -Depth 8 -Compress
Write-GzipJson -Json $assetIndexJson -OutputPath (Join-Path $dataRoot 'asset-index.json.gz')

# Use per-worker queue files so each child receives a small, explicit task list.
$workerTasks = @()
for ($worker = 0; $worker -lt $Workers; $worker++) {
    $assigned = [Collections.Generic.List[object]]::new()
    for ($taskIndex = 0; $taskIndex -lt $tasks.Count; $taskIndex++) { if (($taskIndex % $Workers) -eq $worker) { $assigned.Add($tasks[$taskIndex]) } }
    $taskPath = Join-Path $webRoot ("asset-tasks-{0}.json" -f $worker)
    ConvertTo-Json -InputObject @($assigned) -Depth 6 -Compress | Set-Content -LiteralPath $taskPath -Encoding utf8
    $workerTasks += [pscustomobject]@{ Id = $worker; Path = $taskPath; Count = $assigned.Count }
}

$workerProcesses = @()
foreach ($workerInfo in $workerTasks) {
    $worker = $workerInfo.Id
    $stdout = Join-Path $webRoot ("asset-worker-{0}.out.log" -f $worker)
    $stderr = Join-Path $webRoot ("asset-worker-{0}.err.log" -f $worker)
    $log = Join-Path $webRoot ("asset-worker-{0}.log" -f $worker)
    $arguments = '-NoProfile -ExecutionPolicy Bypass -File "{0}" -TaskListPath "{1}" -WorkerId {2} -FfmpegPath "{3}" -LogPath "{4}"' -f $workerScript, $workerInfo.Path, $worker, $ffmpeg, $log
    $workerProcesses += Start-Process -FilePath 'powershell.exe' -WindowStyle Hidden -PassThru -ArgumentList $arguments -RedirectStandardOutput $stdout -RedirectStandardError $stderr
    Write-Output ("Started export worker {0}: {1} assets." -f $worker, $workerInfo.Count)
}

$start = Get-Date
while (@($workerProcesses | Where-Object { -not $_.HasExited }).Count -gt 0) {
    $finished = @($workerProcesses | Where-Object HasExited).Count
    $lines = foreach ($workerInfo in $workerTasks) {
        $log = Join-Path $webRoot ("asset-worker-{0}.log" -f $workerInfo.Id)
        if (Test-Path -LiteralPath $log) { Get-Content -LiteralPath $log -Tail 1 }
    }
    @("Workers finished: $finished/$Workers", "Elapsed: $([int]((Get-Date)-$start).TotalMinutes) minutes") + $lines | Set-Content -LiteralPath (Join-Path $webRoot 'asset-progress.txt') -Encoding utf8
    Start-Sleep -Seconds 20
    foreach ($process in $workerProcesses) { $process.Refresh() }
}
foreach ($process in $workerProcesses) { $process.Refresh() }
foreach ($workerInfo in $workerTasks) {
    $process = $workerProcesses[$workerInfo.Id]
    if ($process.ExitCode -ne 0) { throw "Asset conversion worker $($workerInfo.Id) failed with exit code $($process.ExitCode). Check HostedAtlas/asset-worker-$($workerInfo.Id).err.log." }
}

$missingOutputs = @($tasks | Where-Object { -not (Test-Path -LiteralPath $_.Destination) -or (Get-Item -LiteralPath $_.Destination).Length -eq 0 })
if ($missingOutputs.Count) { throw ("Image export is incomplete: {0} files are missing or empty. First: {1}" -f $missingOutputs.Count, $missingOutputs[0].Destination) }
$partialFiles = @(Get-ChildItem -LiteralPath $dataRoot -Recurse -File | Where-Object { $_.Name -match '\.partial\.' -or $_.Name -match '\.tmp$' })
if ($partialFiles.Count) { throw ("Incomplete temporary outputs remain: {0}" -f $partialFiles.Count) }

$indexRecords = foreach ($task in $tasks) {
    [pscustomobject]@{
        file = $task.Destination.Substring($dataRoot.Length + 1).Replace('\', '/')
        source = [IO.Path]::GetFileName($task.Source)
        format = [IO.Path]::GetExtension($task.Destination).TrimStart('.').ToLowerInvariant()
        width = $task.Width
        height = $task.Height
        sourceBytes = (Get-Item -LiteralPath $task.Source).Length
        outputBytes = (Get-Item -LiteralPath $task.Destination).Length
        mode = $task.Mode
    }
}
$assetIndexJson = ConvertTo-Json -InputObject ([pscustomobject]@{ schemaVersion = 1; source = 'Silksong bundle-derived preprocessed artwork'; imageCount = $tasks.Count; oversizedPngCount = $oversizedNames.Count; images = @($indexRecords) }) -Depth 8 -Compress
Write-GzipJson -Json $assetIndexJson -OutputPath (Join-Path $dataRoot 'asset-index.json.gz')

$totalBytes = (Get-ChildItem -LiteralPath $dataRoot -Recurse -File | Measure-Object Length -Sum).Sum
$webpCount = @(Get-ChildItem -LiteralPath $dataRoot -Recurse -Filter '*.webp' -File).Count
$pngCount = @(Get-ChildItem -LiteralPath $dataRoot -Recurse -Filter '*.png' -File).Count
$gzipCount = @(Get-ChildItem -LiteralPath $dataRoot -Recurse -Filter '*.gz' -File).Count
$exportManifest = Get-Content -LiteralPath (Join-Path $sourceRoot 'manifest.json') -Raw | ConvertFrom-Json
$primaryRoomImageCount = @($exportManifest.rooms | Where-Object { $_.image }).Count
$roomPreviewCount = @($exportManifest.rooms | Where-Object { $_.previewImage }).Count
$cameraRoomCount = @($exportManifest.rooms | Where-Object { $_.cameraViews -and $_.cameraViews.Count -gt 0 }).Count
$cameraViews = @($exportManifest.rooms | ForEach-Object { $_.cameraViews } | Where-Object { $_ })
$cameraViewCount = $cameraViews.Count
$cappedCameraViewCount = @($cameraViews | Where-Object { $_.resolutionLimited }).Count
$summary = @"
Silksong GauntletSong Atlas data export completed

Data folder: $dataRoot
Room images: $primaryRoomImageCount clean composite renders plus $roomPreviewCount optional preview images, and $cameraViewCount authored camera sections across $cameraRoomCount rooms ($cappedCameraViewCount capped for browser-safe dimensions); $($oversizedNames.Count) oversized originals are retained as PNG and the rest converted to lossless WebP.
Unique bundle-derived artwork atlases: $(@(Get-ChildItem -LiteralPath $artworkRoot -Filter '*.png' -File).Count), included once each for enemy sprite overlays.
Image files: $($webpCount + $pngCount) total ($webpCount WebP, $pngCount PNG); compressed JSON metadata/index files: $gzipCount.
Prepared data size: $([math]::Round($totalBytes / 1GB, 2)) GiB.
The room image assets contain only the clean preprocessed game artwork. Enemy, spawn/check, and Architect/GauntletSong markers are stored in metadata and must be drawn by the viewer.
"@
Write-Output $summary
[IO.File]::WriteAllText((Join-Path $webRoot 'DATA-EXPORT-STATUS.txt'), $summary, [Text.UTF8Encoding]::new($false))
